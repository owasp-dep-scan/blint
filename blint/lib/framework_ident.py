"""Framework and runtime identification from exact evidence (04/B, rule 38).

A framework component is emitted only from a version-bearing string, symbol
set or header that is named here; a file name alone is a *hint* property,
never a component. Every detector states its evidence as
``{what, where, value}`` triples so a consumer can audit the identification
against the bytes it came from, and each one was confirmed on the Android
corpus (tier-0 platform libraries, tier-2 F-Droid apps, tier-3 builds) with
the confirming oracle named in the tests. The committed R1 evidence files
(``tests/data/android/<framework>-evidence.json``, generated by
``tests/scripts/android/extract_identification_evidence.py``) carry the
corpus bytes' side of each comparison.

The module is deliberately string-and-symbol keyed and cheap: the strings
come from LIEF's own string iterator (the same source
``binary_common.binary_strings`` feeds ``parse_strings``), the symbol sets
from the metadata buckets ``parse_symbols`` already built, and the note from
``parse_android_facts``. Nothing here disassembles or reads outside the
parsed object.

Version honesty (rules 11/34): a detector that cannot map its evidence to a
published version emits no version rather than guessing.

Output: identification records stored under ``metadata["frameworks"]``::

    {
        "framework": "ndk-libcxx",
        "version": "r26b",
        "evidence": [
            {"what": ".note.android.ident NDK version",
             "where": "notes", "value": "r26b"},
        ],
        "hints": [],
        "static": False,
    }

Absence of the key means the pass never ran (non-ELF); an empty list means
no framework evidence matched — never "no frameworks present".
"""

